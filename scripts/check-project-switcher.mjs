/** Actual project selector with isolated data/callbacks; no invitation persistence. */
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {build} from 'esbuild';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {act,create} from 'react-test-renderer';
const compiled=(await build({entryPoints:['src/components/ProjectSwitcher.tsx'],bundle:true,write:false,platform:'node',format:'cjs',external:['react'],jsx:'automatic'})).outputFiles[0].text;
const mod={exports:{}};
new Function('require','module','exports',compiled)(createRequire(import.meta.url),mod,mod.exports);
const Switcher=mod.exports.default;
const switched=[],created=[],slugs=[];
const props={currentInvitationId:null,invitations:[],packageId:'free',onSwitch:id=>switched.push(id),onCreate:title=>created.push(title),onUpdateSlug:(...args)=>slugs.push(args)};
// Must render on first account load when no invitations have arrived yet.
const empty=renderToStaticMarkup(React.createElement(Switcher,props));
assert.match(empty,/Undangan/);
assert.match(empty,/0\/3 proyek/);
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
let view;
await act(async()=>{view=create(React.createElement(Switcher,props))});
const content=n=>n.children.map(c=>typeof c==='string'?c:content(c)).join('');
const button=text=>view.root.findAllByType('button').find(n=>content(n).includes(text));
const click=async text=>{const n=button(text);assert.ok(n,`button ${text}`);await act(async()=>n.props.onClick({stopPropagation(){}}))};
await click('Undangan');
await click('Buat Proyek Baru');
assert.equal(button('Buat').props.disabled,true);
await act(async()=>view.root.findByProps({placeholder:'Nama proyek baru...'}).props.onChange({target:{value:'  Rani & Dimas  '}}));
await click('Buat');
assert.deepEqual(created,['Rani & Dimas']);
assert.deepEqual(switched,[]);
const invitations=Array.from({length:3},(_,i)=>({id:`p${i}`,slug:`pasangan-${i}`,title:`Pasangan ${i}`,themeId:'sage-garden',isPublished:i===0}));
await act(async()=>view.update(React.createElement(Switcher,{...props,invitations,currentInvitationId:'p0'})));
await click('Pasangan 0');
assert.equal(button('Buat Proyek Baru'),undefined,'free limit remains three');
assert.match(content(view.root),/Batas proyek tercapai/);
await click('Pasangan 1');
assert.deepEqual(switched,['p1']);
assert.equal(button('Pasangan 1'),undefined,'list closed after selecting another project');
// Enterprise creation remains available; legacy slug editor behaviour stays unchanged.
await act(async()=>view.update(React.createElement(Switcher,{...props,invitations,currentInvitationId:'p0',packageId:'enterprise'})));
await click('Pasangan 0');
assert.ok(button('Buat Proyek Baru'));
assert.equal(button('Ubah slug proyek ini'),undefined);
await act(async()=>view.update(React.createElement(Switcher,{...props,invitations,currentInvitationId:'p0',packageId:'premium'})));
await click('Ubah slug proyek ini');
const slugInput=view.root.findByProps({placeholder:'custom-slug'});
await act(async()=>slugInput.props.onChange({target:{value:'RANI DIMAS'}}));
await act(async()=>button('OK').props.onClick({stopPropagation(){}}));
assert.deepEqual(slugs,[['p0','rani-dimas']]);
await act(async()=>view.unmount());
console.log('PASS: zero-project render/create, trimmed title, selected ID and close, free quota, Enterprise creation and existing legacy slug callback.');
console.log('Limit: React/static markup tests; no browser dropdown keyboard, layout or API persistence QA.');
