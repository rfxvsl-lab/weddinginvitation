/** Render actual analytics with controlled data; no accounts, API or visitor tracking. */
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {build} from 'esbuild';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {act,create} from 'react-test-renderer';
const compiled=(await build({entryPoints:['src/components/AnalyticsDashboard.tsx'],bundle:true,write:false,platform:'node',format:'cjs',external:['react'],jsx:'automatic'})).outputFiles[0].text;
const mod={exports:{}};
new Function('require','module','exports',compiled)(createRequire(import.meta.url),mod,mod.exports);
const Analytics=mod.exports.default;
const rsvps=[{id:'yes',guestName:'Budi',status:'Hadir',paxCount:3,wishes:'Selamat'},{id:'no',guestName:'Sari',status:'Tidak Hadir',paxCount:9,wishes:''},{id:'maybe',guestName:'Dewi',status:'Ragu-ragu',paxCount:2,wishes:''}];
const props={analytics:{viewsCount:12,dailyTraffic:[{date:'2026-09-01',views:5},{date:'2026-11-01',views:7}],visitorLogs:[]},rsvps,onDeleteRSVP(){}};
const html=renderToStaticMarkup(React.createElement(Analytics,props));
assert.doesNotMatch(html,/Real-Time|7 Hari Terakhir/,'do not promise live data or a seven day window');
assert.match(html,/RSVP hadir/);
assert.match(html,/Jumlah balasan menyatakan hadir/);
assert.match(html,/Estimasi orang/);
assert.match(html,/Konfirmasi RSVP bukan check-in/);
assert.match(html,/<svg[^>]*role="img"[^>]*aria-label=/);
assert.match(html,/<table aria-label="Data kunjungan per tanggal"/);
assert.match(html,/scope="row"[^>]*>2026-09-01<\/th><td[^>]*>5<\/td>/);
assert.match(html,/scope="row"[^>]*>2026-11-01<\/th><td[^>]*>7<\/td>/);
const empty=renderToStaticMarkup(React.createElement(Analytics,{...props,analytics:{viewsCount:0,dailyTraffic:[],visitorLogs:[]},rsvps:[]}));
assert.match(empty,/Belum ada data kunjungan per tanggal/);
assert.doesNotMatch(empty,/<svg[^>]*role="img"/,'no empty graph pretending data exists');
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
const deleted=[];
let view;
await act(async()=>{view=create(React.createElement(Analytics,{...props,onDeleteRSVP:id=>deleted.push(id)}))});
const content=n=>n.children.map(c=>typeof c==='string'?c:content(c)).join('');
const kpis=view.root.findAll(n=>n.type==='div'&&n.props.className==='flex items-center justify-between').map(n=>n.parent);
const metric=label=>kpis.find(n=>content(n).includes(label)).findAllByType('p')[0].children.join('');
assert.equal(metric('RSVP hadir'),'1','one reply is not three people');
assert.equal(metric('Estimasi orang'),'3','only attending pax count in estimate');
assert.equal(metric('Absen / Ragu'),'1 / 1');
await act(async()=>view.root.findByProps({'aria-label':'Hapus RSVP dan ucapan dari Sari'}).props.onClick());
assert.deepEqual(deleted,['no'],'delete keeps the selected record id');
await act(async()=>view.unmount());
console.log('PASS: honest traffic labels, named chart + date/value table, empty state, RSVP replies versus pax, existing delete callback.');
console.log('Limit: static markup and isolated React interactions; no browser layout, actual deletion or live tracking tests.');
